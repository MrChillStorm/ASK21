#!/usr/bin/env python3
"""Renders the voice messages of the V8 with the macOS speech synthesizer (`say`, system default voice).

FG9070 speaks with the browser's Web Speech API and no explicit voice, i.e. with the system voice;
rendering with `say` and no -v option gives the same voice. Pass a voice name as the first argument
to use another one. Writes Sounds/lxv8-voice/*.wav and index.nas (clip durations).
"""
import os, subprocess, sys, tempfile, wave

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..', '..', '..', '..'))
OUT = os.path.join(ROOT, 'Sounds', 'lxv8-voice')
os.makedirs(OUT, exist_ok=True)
voice = sys.argv[1:2]

words = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten', 'eleven', 'twelve']
clips = {
    'thermal-average': 'Thermal average',
    'point': 'point',
    'minus': 'minus',
    'traffic': 'Traffic',
    'high': 'high',
    'low': 'low',
    'level': 'level',
}
for i in range(10):
    clips[words[i]] = words[i]
for h in range(1, 13):
    clips['clock-%d' % h] = "%s o'clock" % words[h]
for h in range(100, 1000, 100):
    clips['meters-%d' % h] = '%s hundred meters' % words[h // 100]
for h in range(1000, 4001, 500):
    thousands = ('%s thousand' % words[h // 1000]) + (' five hundred' if h % 1000 else '')
    clips['meters-%d' % h] = thousands + ' meters'

durations = {}
for name, text in sorted(clips.items()):
    with tempfile.NamedTemporaryFile(suffix='.wav', delete=False) as tmp:
        tmp_path = tmp.name
    subprocess.run(['say'] + (['-v', voice[0]] if voice else []) + ['--file-format=WAVE', '--data-format=LEI16@22050', '-o', tmp_path, text], check=True)
    dst = os.path.join(OUT, name + '.wav')
    with wave.open(tmp_path) as w:
        frames, rate = w.getnframes(), w.getframerate()
        data = w.readframes(frames)
        params = w.getparams()
    os.unlink(tmp_path)
    # trim silence at both ends (say leaves some), keep a little tail so the words do not run together
    import array
    a = array.array('h'); a.frombytes(data)
    thr = 400
    lo = next((i for i, v in enumerate(a) if abs(v) > thr), 0)
    hi = len(a) - next((i for i, v in enumerate(reversed(a)) if abs(v) > thr), 0)
    lo = max(0, lo - int(rate * 0.01)); hi = min(len(a), hi + int(rate * 0.02))
    with wave.open(dst, 'wb') as w:
        w.setparams(params); w.setnframes(0)
        w.writeframes(a[lo:hi].tobytes())
    durations[name] = (hi - lo) / rate
with open(os.path.join(OUT, 'index.nas'), 'w') as f:
    f.write('# generated by Models/Interior/Panel/Instruments/lx-v8/src/make_voice.py\nvar voice_clips = {\n')
    for k, v in sorted(durations.items()):
        f.write('\t"%s": %.3f,\n' % (k, v))
    f.write('};\n')
print(len(durations), 'clips,', '%.2f' % sum(durations.values()), 's in total')
import runpy
runpy.run_path(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'make_sound_entries.py'))
