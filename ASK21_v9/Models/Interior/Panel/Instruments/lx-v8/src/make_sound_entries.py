#!/usr/bin/env python3
"""Defines every voice clip of Sounds/lxv8-voice/ as a one-shot sound in Sounds/ask21-sound.xml.

A clip plays when /instrumentation/lxv8/voice/clip becomes its number (lxv8-core.nas sets it, one clip after the other,
and back to 0 in between). Writes the entries between the LXV8-VOICE markers of ask21-sound.xml and the numbers into
Sounds/lxv8-voice/index.nas (together with the durations)."""
import os, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..', '..', '..', '..'))
VOICE = os.path.join(ROOT, 'Sounds', 'lxv8-voice')
XML = os.path.join(ROOT, 'Sounds', 'ask21-sound.xml')

idx_file = open(os.path.join(VOICE, 'index.nas')).read()
durations = dict((m.group(1), float(m.group(2))) for m in re.finditer(r'"([^"]+)":\s*([\d.]+)', idx_file.split('var voice_clips')[1].split('};')[0]))
names = sorted(durations)
number = dict((n, i + 1) for i, n in enumerate(names))

entries = ['\t\t<!-- LXV8-VOICE-BEGIN: generated by Models/Interior/Panel/Instruments/lx-v8/src/make_sound_entries.py -->']
for n in names:
    tag = 'lxv8-voice-' + n
    entries.append('''\t\t<%(tag)s>
\t\t\t<name>%(tag)s</name>
\t\t\t<mode>once</mode>
\t\t\t<path>lxv8-voice/%(n)s.wav</path>
\t\t\t<condition>
\t\t\t\t<equals>
\t\t\t\t\t<property>instrumentation/lxv8/voice/clip</property>
\t\t\t\t\t<value>%(i)d</value>
\t\t\t\t</equals>
\t\t\t</condition>
\t\t\t<volume>
\t\t\t\t<property>instrumentation/lxv8/audio/voice-volume</property>
\t\t\t\t<factor>1</factor>
\t\t\t\t<max>1</max>
\t\t\t</volume>
\t\t\t<position>
\t\t\t\t<x>-3.35</x>
\t\t\t\t<y>0</y>
\t\t\t\t<z>0.7</z>
\t\t\t</position>
\t\t\t<reference-dist>0.5</reference-dist>
\t\t\t<max-dist>2.0</max-dist>
\t\t</%(tag)s>''' % {'tag': tag, 'n': n, 'i': number[n]})
entries.append('\t\t<!-- LXV8-VOICE-END -->')
block = '\n'.join(entries)

s = open(XML, encoding='latin-1').read()
if 'LXV8-VOICE-BEGIN' in s:
    s = re.sub(r'\t\t<!-- LXV8-VOICE-BEGIN.*?LXV8-VOICE-END -->', lambda m: block, s, flags=re.S)
else:
    marker = '\t\t</lxv8-tone>\n'
    assert marker in s
    s = s.replace(marker, marker + '\n' + block + '\n')
open(XML, 'w', encoding='latin-1').write(s)

with open(os.path.join(VOICE, 'index.nas'), 'w') as f:
    f.write('# generated by Models/Interior/Panel/Instruments/lx-v8/src/make_voice.py and make_sound_entries.py\n')
    f.write('# duration of every clip in seconds, and the number the sound system plays it for (voice/clip)\n')
    f.write('var voice_clips = {\n')
    for n in names: f.write('\t"%s": %.3f,\n' % (n, durations[n]))
    f.write('};\nvar voice_numbers = {\n')
    for n in names: f.write('\t"%s": %d,\n' % (n, number[n]))
    f.write('};\n')
print(len(names), 'clips')
