#!/usr/bin/env python3
"""Models/Interior/yawstring/: the yaw strings on the front and rear canopy, as real geometry.

The stock wool thread (Aircraft/Instruments-3d/glider/wool-thread) is a red line painted on a transparent disc and turned
by rotating the texture. The transparency makes FlightGear treat it as translucent, which draws nothing on macOS with the
compositor. The front disc was also tilted about 15 deg, flatter than the canopy there (about 20 deg and steepening),
so the end of the thread ran into the glass and the pilot saw it almost end-on: it looked very short whenever it pointed
straight back.

Here the thread is an opaque red strand (3 x 1 mm, 120 mm long) under a small piece of tape, lying on the outside of the
canopy and turning about the canopy's normal at the tape (yawstring.xml, property instrumentation/yawstring = sideslip).
The script finds the outer canopy surface at the centre line where the stock strings were taped (interior.xml) and
prints the offsets for interior.xml.

Model frame of yawstring.ac: x along the string (aft, along the canopy), y right, z out of the canopy.
AC files store (x aft, y up, z = -right)."""
import math, os
HERE = os.path.dirname(os.path.abspath(__file__))
MODELS = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
OUT = os.path.join(MODELS, 'Interior', 'yawstring')

LENGTH, WIDTH, THICK = 0.120, 0.003, 0.001       # the strand
TAPE_L, TAPE_W, TAPE_T = 0.018, 0.012, 0.0003    # the tape over its front end
LIFT = 0.0015                                    # gap between canopy and strand
ROOTS = {'yawstring.F': ('canopy.F.glass', -3.43276), 'yawstring.R': ('canopy.R.glass', -2.22)}   # x of the tape (stock)

def glass(name):
    """Triangles of a canopy glass of ask21.ac in the FlightGear frame (x aft, y right, z up)."""
    L = open(os.path.join(MODELS, 'ask21.ac')).read().split('\n'); s = L.index('name "%s"' % name)
    nvl = next(k for k in range(s, len(L)) if L[k].startswith('numvert'))
    n = int(L[nvl].split()[1])
    v = [(lambda x, y, z: (x, -z, y))(*map(float, L[nvl + 1 + k].split()[:3])) for k in range(n)]
    j = nvl + 1 + n; ns = int(L[j].split()[1]); j += 1; tris = []
    for _ in range(ns):
        nr = int(L[j + 2].split()[1]); idx = [int(l.split()[0]) for l in L[j + 3:j + 3 + nr]]; j += 3 + nr
        tris += [(v[idx[0]], v[idx[k]], v[idx[k + 1]]) for k in range(1, nr - 1)]
    return tris

def surface_z(tris, x, y=0.0):
    """Height of the outer canopy surface above (x, y): the highest hit of a vertical line."""
    best = None
    for a, b, c in tris:
        d = (b[0] - a[0]) * (c[1] - a[1]) - (c[0] - a[0]) * (b[1] - a[1])
        if abs(d) < 1e-12: continue
        u = ((x - a[0]) * (c[1] - a[1]) - (c[0] - a[0]) * (y - a[1])) / d
        w = ((b[0] - a[0]) * (y - a[1]) - (x - a[0]) * (b[1] - a[1])) / d
        if u >= 0 and w >= 0 and u + w <= 1:
            z = a[2] + u * (b[2] - a[2]) + w * (c[2] - a[2])
            best = z if best is None else max(best, z)
    return best

def box(x0, x1, w, z0, z1):
    """Vertices and quads of a box, the faces pointing outwards."""
    v = [(x, y, z) for x in (x0, x1) for y in (-w / 2, w / 2) for z in (z0, z1)]
    f = [(0, 1, 3, 2), (4, 6, 7, 5), (0, 4, 5, 1), (2, 3, 7, 6), (0, 2, 6, 4), (1, 5, 7, 3)]
    return v, f

def obj(name, mat, v, f):
    o = ['OBJECT poly', 'name "%s"' % name, 'numvert %d' % len(v)]
    o += ['%.6f %.6f %.6f' % (x, z, -y) for x, y, z in v]           # FlightGear frame -> AC
    o.append('numsurf %d' % len(f))
    for q in f:
        o += ['SURF 0x00', 'mat %d' % mat, 'refs %d' % len(q)] + ['%d 0 0' % i for i in q]
    return o + ['kids 0']

os.makedirs(OUT, exist_ok=True)
ac = ['AC3Db',
      'MATERIAL "wool" rgb 0.85 0.03 0.02  amb 0.85 0.03 0.02  emis 0 0 0  spec 0.05 0.05 0.05  shi 4  trans 0',
      'MATERIAL "tape" rgb 0.88 0.88 0.85  amb 0.88 0.88 0.85  emis 0 0 0  spec 0.4 0.4 0.4  shi 32  trans 0',
      'OBJECT world', 'kids 2']
ac += obj('thread', 0, *box(0.0, LENGTH, WIDTH, LIFT, LIFT + THICK))
ac += obj('tape', 1, *box(-TAPE_L / 2, TAPE_L / 2, TAPE_W, LIFT + THICK, LIFT + THICK + TAPE_T))
open(os.path.join(OUT, 'yawstring.ac'), 'w').write('\n'.join(ac) + '\n')

# The string turns with the airflow angle at the string (Nasal/yawstring.nas: [0] front, [1] rear, set per string in
# interior.xml): wind from the right (positive) blows its free end to the left. Positive rotations about +z turn +x
# (aft) towards +y (right), so the factor is -1.
open(os.path.join(OUT, 'yawstring.xml'), 'w').write('''<?xml version="1.0"?>
<!-- Yaw string: generated by Models/Interior/Panel/src/make_yawstring.py -->
<PropertyList>
	<path>yawstring.ac</path>
	<params>
		<use-prop type="string">instrumentation/yawstring[0]</use-prop>
	</params>
	<animation>
		<type>noshadow</type>
		<object-name>thread</object-name>
		<object-name>tape</object-name>
	</animation>
	<animation>
		<type>rotate</type>
		<object-name>thread</object-name>
		<property alias="../../params/use-prop"/>
		<factor>-1</factor>
		<axis>
			<z>1</z>
		</axis>
	</animation>
</PropertyList>
''')

# Offsets for interior.xml: the string lies along the chord from the tape to the canopy surface one string length aft
# (the canopy curves, so the slope at the tape would put the end into the glass); pitch-deg is minus that slope.
for name, (g, x) in ROOTS.items():
    tris = glass(g)
    z0 = surface_z(tris, x); dx = LENGTH
    for _ in range(20):
        z1 = surface_z(tris, x + dx); dx = LENGTH * dx / math.hypot(dx, z1 - z0)
    slope = math.degrees(math.atan2(z1 - z0, dx))
    print('%s: x-m %.4f  z-m %.4f  pitch-deg %.1f' % (name, x, z0, -slope))
